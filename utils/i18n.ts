const MESSAGES: Record<Locale, Record<string, string>> = { 'zh-CN': zh, en };

export interface I18n {
  t: (key: string, params?: Record<string, string | number>) => string;
  isZh: ComputedRef<boolean>;
  locale: ComputedRef<Locale>;
}

/** 渲染一条文案：按 locale 取字典，缺键回退英文，再回退 key 本身 */
function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let str = MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

/** 组件/函数内取翻译：t 会跟踪 settings.lang，语言切换时模板自动重渲染 */
export function useI18n(): I18n {
  const { settings } = useSettings();
  const locale = computed<Locale>(() => {
    const l = settings.lang;
    if (l === 'zh-CN' || l === 'en') return l;
    const nav = (typeof navigator !== 'undefined' ? navigator.language : '') || '';
    return nav.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
  });
  const isZh = computed(() => locale.value === 'zh-CN');
  const t = (key: string, params?: Record<string, string | number>) => translate(locale.value, key, params);
  return { t, isZh, locale };
}
